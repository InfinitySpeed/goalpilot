import unittest
from app import Service
from goalpilot_support import JourneyMixin, rejects

class Incidents(JourneyMixin,unittest.TestCase):
 def setUp(self):self.open_service(Service)
 def test_journey(self):
  def flow(c):
   self.assertEqual(c('team.put',id='t',members=['b','a','a']),{'id':'t','members':['a','b']})
   self.assertEqual(c('policy.put',id='p',response=5,resolve=10),{'id':'p','response':5,'resolve':10})
   payload=dict(id='i',team='t',policy='p',now=0,title='café',key='k')
   original=c('incident.open',**payload)
   self.assertEqual(original,dict(id='i',team='t',title='café',status='open',owner=None,revision=1,level=0,acknowledged=None,resolved=None,paused=False))
   def step(op,rev,now,**kw):return c(op,id='i',expected_revision=rev,now=now,**kw)
   self.assertEqual(step('incident.assign',1,1,owner='a')['revision'],2)
   rejects(lambda:c('team.put',id='t',members=['b']))
   rejects(lambda:step('incident.ack',1,2))
   self.assertTrue(c('incident.inspect',id='i',now=5)['response_breached'])
   self.assertEqual(step('escalate',2,5)['level'],1)
   rejects(lambda:step('escalate',3,5))
   step('incident.pause',3,6)
   self.assertEqual(c('incident.inspect',id='i',now=100)['elapsed'],6)
   rejects(lambda:step('escalate',4,5))
   step('incident.resume',4,16)
   self.assertEqual(step('incident.ack',5,17)['acknowledged'],17)
   c('policy.put',id='p',response=50,resolve=100)
   self.assertTrue(c('incident.inspect',id='i',now=20)['resolve_breached'])
   step('escalate',6,20)
   step('incident.resolve',7,21)
   self.assertEqual(c('incident.inspect',id='i',now=100)['elapsed'],11)
   snapshot=c('backup')
   step('incident.reopen',8,30)
   self.assertEqual(c('incident.inspect',id='i',now=30)['elapsed'],0)
   self.assertEqual(c('incident.open',**payload),original)
   rejects(lambda:c('incident.open',**dict(payload,title='changed')))
   c('restore',state=snapshot)
   self.assertEqual(c('incident.inspect',id='i',now=100)['status'],'resolved')
   rejects(lambda:c('incident.import',incidents=[dict(payload,id='j',key='j'),dict(payload,id='z',key='k')]))
   self.assertEqual(len(c('incident.list')),1)
   self.assertEqual(c('incident.import',incidents=[dict(payload,id='j',key='j')]),{'imported':1})
   self.assertEqual([r['id'] for r in c('incident.list',team='t',status='open')],['j'])
   rejects(lambda:c('policy.put',id='bad',response=True,resolve=10))
  self.assertJourney(flow)
 def test_restore_and_race(self):
  self.c('team.put',id='t',members=['a'])
  self.c('policy.put',id='p',response=1,resolve=2)
  payload=dict(id='i',team='t',policy='p',now=0,title='x',key='k')
  results=self.race(*[('incident.open',payload)]*2)
  self.assertTrue(all(ok for ok,_ in results));self.assertEqual(results[0][1],results[1][1])
  results=self.race(*[('incident.assign',dict(id='i',owner='a',expected_revision=1,now=1))]*2)
  self.assertEqual(sum(ok for ok,_ in results),1)
  self.restart();self.assertEqual(self.c('incident.inspect',id='i',now=2)['revision'],2)
  self.assertCorruptions(lambda b:b['state']['incidents']['i'].update(level=99))
